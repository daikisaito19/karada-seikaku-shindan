// 内部スコアの9軸。ユーザーには基本的に見せず、タイプ判定と4軸メーターの算出だけに使う。
//
// v4でJIN(津液不足)を独立させ、8軸→9軸になった。
// 旧8軸ではBLが「栄養不足」と「うるおい不足」を、YINが「ほてり」と「乾燥」を
// それぞれ兼任していたため、09うるおい不足と06ほてほてが分離できなかった。
// v4では「乾燥」の担当をJINに一本化し、BLは材料不足、YINは熱がこもる側だけを見る。
export type ScoreAxis =
  | "QI" // 気虚（エネルギー不足）
  | "SP" // 脾気虚（消化・回復力の弱さ）
  | "ST" // 気滞・肝鬱（ストレス反応）
  | "BL" // 血虚（血・栄養という「材料」の不足）
  | "JIN" // 津液不足（うるおいの不足・乾燥）
  | "YANG" // 陽虚（冷え）
  | "YIN" // 陰虚（熱がこもる・のぼせ）
  | "DAM" // 痰湿（水分・老廃物の溜め込み）
  | "STA"; // 血瘀（血の滞り）

export const SCORE_AXES: ScoreAxis[] = [
  "QI",
  "SP",
  "ST",
  "BL",
  "JIN",
  "YANG",
  "YIN",
  "DAM",
  "STA",
];

export type ScoreDelta = Partial<Record<ScoreAxis, number>>;
