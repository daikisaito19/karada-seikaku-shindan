/**
 * 4軸メーターの「表示用スケール」。判定には一切使わない。
 *
 * エネルギー・流れ・うるおいの3本は `100 - 不足度` という一方向の量なので、
 * 生の値をそのまま出すと、ほとんどの人が右寄り（HIGH / FLOW / WET）になる。
 * 実測では、現実的な回答傾向で
 *   エネルギーがHIGH側 99% / 流れがFLOW側 94% / うるおいがWET側 95%
 * となり、中央の50が「平均的な人」を意味していなかった。
 *
 * そこで、生の値を「想定回答者の分布の中での位置」に置き換える。
 * 50が本当に真ん中になるので、メーターは
 * 「点数が高い / 低い」ではなく「みんなと比べてどちら寄りか」として読める。
 *
 * 温度だけは変換しない。
 * 温度は `50 + (YIN - YANG)/2` という対立2軸の差で、50がもともと正しい中立点。
 * ここを分布で正規化すると、熱の申告が一切ない回答（YIN=0 かつ YANG=0）が
 * 「HOT寄り」と出るなど、意味のない信号が生まれることを確認している。
 */

export type ScaledAxis = "energy" | "flow" | "moisture";
export const SCALED_AXES: ScaledAxis[] = ["energy", "flow", "moisture"];

