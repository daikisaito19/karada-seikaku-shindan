/** 生の値を、母集団内での位置に置き換える */
export function scaleAxisValue(axis: ScaledAxis, value: number): number {
  const table = DISPLAY_SCALE[axis];
  const i = Math.max(0, Math.min(100, Math.round(value)));
  return table[i] ?? i;
}

/**
 * 4軸をまとめて表示用に変換する。温度はそのまま通す。
 * computeVisibleAxes() の戻り値を、AxisMeter に渡す直前に通すだけ。
 */
export function scaleVisibleAxes(v: VisibleAxes): VisibleAxes {
  return {
    energy: scaleAxisValue("energy", v.energy),
    flow: scaleAxisValue("flow", v.flow),
    temperature: v.temperature,
    moisture: v.moisture,
  };
}
