import type { VisibleAxes } from "./scoring";

/**
 * 4軸メーターの「表示用スケール」。判定には一切使わない。
 *
 * エネルギーと流れは `100 - 不足度` という一方向の量なので、
 * 生の値をそのまま出すと、ほとんどの人が右寄り（HIGH / FLOW）になる。
 * 実測では、現実的な回答傾向で エネルギー88% / 流れ87% が中央より右に寄り、
 * 中央の50が「平均的な人」を意味していなかった。
 *
 * そこで、生の値を「想定回答者の分布の中での位置」に置き換える。
 * 50が本当に真ん中になるので、メーターは
 * 「点数が高い / 低い」ではなく「みんなと比べてどちら寄りか」として読める。
 *
 * 温度とうるおいは変換しない。
 * この2本は対立する2軸の差をとる双方向軸で、50がもともと正しい中立点になっている。
 *   温度     = 50 + (YIN - YANG)/2
 *   うるおい = 50 + (DAM - JIN)/2
 * ここを分布で正規化すると、その軸の申告が一切ない回答（例: YIN=0 かつ YANG=0）まで
 * どちらかに寄せてしまい、意味のない信号が生まれることを確認している。
 * うるおいは、C2で BL が抜けて DAM と JIN の差になった時点で
 * 温度と同じ性質になったため、温度と同じ扱いにしている
 * （実測でも中央値50 / 53%が「まんなか」判定に収まり、正規化の必要がない）。
 */

export type ScaledAxis = "energy" | "flow";
export const SCALED_AXES: ScaledAxis[] = ["energy", "flow"];

